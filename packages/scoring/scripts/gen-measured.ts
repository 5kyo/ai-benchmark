// 실측 데이터 생성기: raw/ 스냅샷의 규칙 점수 + scoring/outbox/<model>/의 축 C 점수를
// 합쳐 packages/web/src/lib/data/measured.ts (measuredCompanies)를 만든다.
// 사용: pnpm exec tsx packages/scoring/scripts/gen-measured.ts
import { readFileSync, readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadCompanies, scoreRules, type RawSnapshot } from "@ai-benchmark/crawler";
import type { MetricScore } from "@ai-benchmark/core";
import {
  parseAndValidate, toLlmScores, loadLlmMetrics, llmAxisByKey,
  buildSnapshotFile, snapshotFilename, localDateString, extractFingerprint,
} from "../src/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");

const companies = loadCompanies(resolve(root, "config/companies.yaml"));
const weightsPath = resolve(root, "config/weights.yaml");
const llmKeys = loadLlmMetrics(weightsPath).map((m) => m.key);
const axisByKey = llmAxisByKey(weightsPath);
const outboxRoot = resolve(root, "scoring/outbox");
const models = existsSync(outboxRoot) ? readdirSync(outboxRoot) : [];

function pickLatest(files: string[]): string | null {
  const j = files.filter((f) => f.endsWith(".json")).sort();
  return j.length ? j[j.length - 1] : null;
}

// 날짜별 아카이브 키. --date=YYYY-MM-DD 로 지정(백필용), 없으면 오늘.
const RUBRIC_VERSION = "rubric_v1";
const dateArg = process.argv.find((a) => a.startsWith("--date="));
const snapshotDate = dateArg ? dateArg.slice("--date=".length) : localDateString(new Date());
const snapshotsDir = resolve(root, "snapshots");
// 콘텐츠 지문 아카이브: 변화 감지(detect-changes)의 비교 재료.
const contentDir = resolve(snapshotsDir, "content", snapshotDate);
mkdirSync(contentDir, { recursive: true });
let fingerprintCount = 0;

const records = companies.map((c) => {
  const scores: MetricScore[] = [];

  const rawDir = resolve(root, "raw", c.slug);
  if (existsSync(rawDir)) {
    const latest = pickLatest(readdirSync(rawDir));
    if (latest) {
      const snap = JSON.parse(readFileSync(resolve(rawDir, latest), "utf8")) as RawSnapshot;
      scores.push(...scoreRules(snap));
      if (snap.homepage && snap.homepage.status === 200) {
        const fp = extractFingerprint(snap.homepage.body, {
          slug: c.slug, date: snapshotDate, url: c.homepageUrl,
        });
        writeFileSync(resolve(contentDir, `${c.slug}.json`), JSON.stringify(fp, null, 2));
        fingerprintCount += 1;
      }
    }
  }

  for (const model of models) {
    const file = resolve(outboxRoot, model, `${c.slug}.json`);
    if (!existsSync(file)) continue;
    try {
      const out = parseAndValidate(readFileSync(file, "utf8"), llmKeys);
      scores.push(...toLlmScores(out, axisByKey));
    } catch (e) {
      console.error(`[${c.slug}/${model}] validation failed: ${(e as Error).message}`);
    }
  }

  return {
    slug: c.slug,
    name: c.name,
    homepageUrl: c.homepageUrl,
    isSelf: c.isSelf,
    category: c.category,
    region: c.region,
    description: c.description,
    scores,
  };
});

const banner =
  `// AUTO-GENERATED by packages/scoring/scripts/gen-measured.ts — do not edit by hand.\n` +
  `// 실측 데이터: 크롤러 규칙 점수(A/B/D) + Claude 축 C 채점.\n`;
const body =
  `import type { CompanyRecord } from "./types.js";\n\n` +
  `export function measuredCompanies(): CompanyRecord[] {\n` +
  `  return ${JSON.stringify(records, null, 2)} as CompanyRecord[];\n}\n`;
writeFileSync(resolve(root, "packages/web/src/lib/data/measured.ts"), banner + body);
console.log(`wrote measured.ts with ${records.length} companies (models: ${models.join(", ") || "none"})`);

// 날짜별 전 회사 스냅샷 아카이브.
mkdirSync(snapshotsDir, { recursive: true });
const snapshot = buildSnapshotFile(records, {
  date: snapshotDate,
  generatedAt: new Date().toISOString(),
  rubricVersion: RUBRIC_VERSION,
});
writeFileSync(
  resolve(snapshotsDir, snapshotFilename(snapshotDate)),
  JSON.stringify(snapshot, null, 2),
);
console.log(`wrote snapshots/${snapshotFilename(snapshotDate)} (${records.length} companies)`);
console.log(`wrote snapshots/content/${snapshotDate}/ (${fingerprintCount} fingerprints)`);
